// Ghidra headless post-script: export functions as C-like pseudocode.
import java.io.File;
import java.io.PrintWriter;
import java.io.BufferedWriter;
import java.io.FileWriter;

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;

public class ExportDecompilation extends GhidraScript {
    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 1) {
            printerr("Usage: ExportDecompilation.java <output-directory>");
            return;
        }

        File outDir = new File(args[0]);
        if (!outDir.exists() && !outDir.mkdirs()) {
            printerr("Could not create output directory: " + outDir);
            return;
        }

        File outputFile = new File(outDir, "decompiled.c");
        DecompInterface decompiler = new DecompInterface();
        decompiler.toggleCCode(true);
        decompiler.toggleSyntaxTree(true);

        if (!decompiler.openProgram(currentProgram)) {
            printerr("Could not initialize decompiler for " + currentProgram.getName());
            decompiler.dispose();
            return;
        }

        int total = 0;
        int completed = 0;
        try (PrintWriter out = new PrintWriter(new BufferedWriter(new FileWriter(outputFile)))) {
            out.println("/*");
            out.println(" * Decompiled pseudocode generated by Ghidra.");
            out.println(" * This is NOT the original source code; review and validate before relying on it.");
            out.println(" */");

            FunctionIterator functions = currentProgram.getFunctionManager().getFunctions(true);
            while (functions.hasNext() && !monitor.isCancelled()) {
                Function function = functions.next();
                total++;
                out.println("\\n/* ============================================================ */");
                out.println("/* Function: " + function.getName() + " */");
                out.println("/* Entry: " + function.getEntryPoint() + " */");
                out.println("/* ============================================================ */");

                DecompileResults result = decompiler.decompileFunction(function, 60, monitor);
                if (result != null && result.decompileCompleted() && result.getDecompiledFunction() != null) {
                    out.println(result.getDecompiledFunction().getC());
                    completed++;
                } else {
                    out.println("/* Decompilation unavailable: " +
                        (result == null ? "no result" : result.getErrorMessage()) + " */");
                }
                out.println();
                if (total % 100 == 0) {
                    out.flush();
                    println("Processed " + total + " functions...");
                }
            }
        } finally {
            decompiler.dispose();
        }

        println("Functions encountered: " + total);
        println("Functions decompiled: " + completed);
        println("Pseudocode written to: " + outputFile.getAbsolutePath());
    }
}
